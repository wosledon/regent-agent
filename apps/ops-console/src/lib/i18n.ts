const missingKeyFallbacks = { 'zh-CN': '未知', 'en-US': 'Unknown' } as const;

function missingKeyFallback(): string {
  const locale = resolveLocale(i18n.resolvedLanguage ?? i18n.language);
  const resource = i18n.getResource(locale, 'translation', 'common.unknown');
  return typeof resource === 'string' && resource.trim() ? resource : missingKeyFallbacks[locale];
}

